def split_description(desc: str) -> tuple[str, str]:
    """Split the `description` field into (change_summary, rationale).

    The rationale is the trailing bracketed tail ``[...]``. Descriptions can
    contain unrelated brackets like ``hneigh[][2]`` or ``x[j]`` mid-sentence,
    so we scan backward from the final ``]`` with a depth counter to find the
    matching opening bracket.
    """
    desc = (desc or "").strip()
    if not desc.endswith("]"):
        return desc, ""
    depth = 0
    for i in range(len(desc) - 1, -1, -1):
        c = desc[i]
        if c == "]":
            depth += 1
        elif c == "[":
            depth -= 1
            if depth == 0:
                return desc[:i].rstrip(), desc[i + 1 : -1].strip()
    return desc, ""


def rst_escape(text: str) -> str:
    return (text or "").replace("|", "\\|").replace("`", "\\`")


def rst_title(text: str, char: str) -> str:
    return f"{text}\n{char * max(len(text), 3)}\n"


def copy_tree(src: Path, dst: Path) -> None:
    if src.exists():
        if dst.exists():
            shutil.rmtree(dst)
        shutil.copytree(src, dst)


def list_relative_files(root: Path) -> list[str]:
    if not root.is_dir():
        return []
    return [
        str(path.relative_to(root)).replace("\\", "/")
        for path in sorted(root.rglob("*"))
        if path.is_file()
    ]


def copy_contract(optimize_dir: Path, out_dir: Path) -> list[str]:
    dst = out_dir / "contract"
    dst.mkdir(parents=True, exist_ok=True)
    copied: list[str] = []
    autogen = optimize_dir / "autogen"
    if autogen.exists():
        for name in (
            "benchmark.yaml",
            "benchmark_runner.py",
            "goal.md",
            "goal_inputs.json",
            "goal_analysis.json",
            "goal_mode.json",
            "run_optimize.sh",
            "setup_env.sh",
        ):
            src = autogen / name
            if src.exists():
                shutil.copy2(src, dst / name)
                copied.append(name)
    for name in ("program.md", "memory.md", "worker_memory.md"):
        src = optimize_dir / name
        if src.exists():
            shutil.copy2(src, dst / name)
            copied.append(name)
    return copied


def copy_benchmark_inputs(optimize_dir: Path, out_dir: Path) -> list[str]:
    src_root = optimize_dir / "inputs" / "all"
    input_files = list_relative_files(src_root)
    if not input_files:
        return []
    dst_root = out_dir / "inputs" / "all"
    copy_tree(src_root, dst_root)
    return input_files



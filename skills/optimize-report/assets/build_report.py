def load_json_file(path: Path) -> dict:
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text())
    except (json.JSONDecodeError, OSError):
        return {}


def read_text_safe(path: Path, limit: Optional[int] = None) -> str:
    if not path.exists():
        return ""
    try:
        data = path.read_text(errors="replace")
    except OSError:
        return ""
    if limit and len(data) > limit:
        return data[:limit] + f"\n... (truncated, full file {len(data)} bytes)"
    return data


def extract_markdown_sections(text: str) -> dict[str, str]:
    sections: dict[str, str] = {}
    current_heading = ""
    current_lines: list[str] = []
    for line in text.splitlines():
        match = _HEADING_RE.match(line)
        if match:
            if current_heading:
                sections[current_heading] = "\n".join(current_lines).strip()
            current_heading = match.group(2).strip().lower()
            current_lines = []
        else:
            current_lines.append(line)
    if current_heading:
        sections[current_heading] = "\n".join(current_lines).strip()
    return sections


def goal_first_line(goal_text: str, heading: str) -> str:
    body = extract_markdown_sections(goal_text).get(heading.lower(), "")
    return body.splitlines()[0].strip() if body else ""


def goal_code_blocks(goal_text: str, heading: str) -> list[str]:
    body = extract_markdown_sections(goal_text).get(heading.lower(), "")
    blocks: list[str] = []
    current: list[str] | None = None
    for line in body.splitlines():
        stripped = line.strip()
        if stripped.startswith("```"):
            if current is None:
                current = []
            else:
                blocks.append("\n".join(current).strip())
                current = None
            continue
        if current is not None:
            current.append(line)
    return [block for block in blocks if block]


def text_references_filename(text: str, filename: str) -> bool:
    if not text or not filename:
        return False
    pattern = re.compile(
        rf"(?<![A-Za-z0-9_./-]){re.escape(filename)}(?![A-Za-z0-9_./-])"
    )
    return pattern.search(text) is not None


def goal_workload_input_files(goal_text: str, benchmark_input_files: list[str]) -> list[str]:
    body = extract_markdown_sections(goal_text).get("representative workloads", "")
    if not body or not benchmark_input_files:
        return []

    referenced: list[str] = []
    for rel_path in benchmark_input_files:
        basename = Path(rel_path).name
        candidates = [rel_path]
        if basename != rel_path:
            candidates.append(basename)
        if any(text_references_filename(body, candidate) for candidate in candidates):
            referenced.append(rel_path)
    return referenced


def yaml_scalar(text: str, key: str) -> str:
    pattern = re.compile(rf"^{re.escape(key)}:\s*(.+?)\s*$", re.MULTILINE)
    match = pattern.search(text)
    if not match:
        return ""
    value = match.group(1).split(" #", 1)[0].strip()
    return value.strip("\"'")


def normalize_language(raw: str) -> str:
    value = (raw or "").strip().lower()
    if not value:
        return ""
    if "python" in value or value == "py":
        return "python"
    if "fortran" in value or value in {"f90", "f77", "f95"}:
        return "fortran"
    if value in {"cpp", "c++", "cxx", "c"} or "c/c++" in value:
        return "cpp"
    return value


def infer_language_from_goal_path(goal_path: str) -> str:
    name = Path(goal_path or "").name.lower()
    if name.startswith(("python-", "py-")):
        return "python"
    if name.startswith(("fortran-", "f90-", "f77-")):
        return "fortran"
    if name.startswith(("cpp-", "cxx-", "c-")):
        return "cpp"
    return ""


def launcher_for_language(language: str) -> Optional[str]:
    normalized = normalize_language(language)
    if normalized == "python":
        return "fermilink-optimize-python"
    if normalized in {"cpp", "fortran"}:
        return "fermilink-optimize-cpp"
    return None


